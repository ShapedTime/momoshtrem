// Extracts the Lucide icons the prototype uses into assets/js/icons.js.
// Run: node tools/build-icons.mjs /path/to/lucide-static/icons
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const dir = process.argv[2];
const names = `search compass library library-big activity settings log-out user x chevron-left chevron-right chevron-down chevron-up
arrow-left arrow-right arrow-up-right arrow-down arrow-up plus check check-check circle-check circle-alert triangle-alert info copy magnet
download upload pause play trash-2 rotate-cw refresh-cw thumbs-up thumbs-down eye-off eye heart star calendar calendar-clock clock film tv
tv-minimal tv-minimal-play popcorn clapperboard sparkles sparkle wand-sparkles send message-circle history sliders-horizontal list-filter
arrow-up-down layout-grid list rows-3 ellipsis ellipsis-vertical external-link link folder folder-open file-video file file-text captions
languages gauge server database cpu hard-drive zap users flame gem moon sun monitor lock key-round command corner-down-left hash
list-ordered bot search-x scan-search shield-alert ban signal circle-pause circle-play square-play pencil undo-2 grip-vertical
chevrons-up-down loader-circle circle-dashed circle-dot cast bell globe flag award lightbulb timer hourglass paw-print cat share-2
clipboard-check house heart-crack skip-forward list-video panel-right-open panel-left wifi-off cloud-off plug unplug badge-check
square-check-big square ticket mic-vocal music-2 type replace split merge scissors bookmark bookmark-check circle-x circle-help
arrow-right-left sliders-vertical text-search folder-tree layers ear shapes package party-popper`.split(/\s+/).filter(Boolean);
const out = {}; const missing = [];
for (const n of names) {
  const f = `${dir}/${n}.svg`;
  if (!existsSync(f)) { missing.push(n); continue; }
  const s = readFileSync(f, 'utf8');
  const inner = s.slice(s.indexOf('>', s.indexOf('<svg')) + 1, s.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').trim();
  out[n] = inner;
}
writeFileSync('assets/js/icons.js', `/* Lucide icons (ISC licence, lucide.dev) v0.460.0, subset. Generated by tools/build-icons.mjs. */\nwindow.ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"')};\n`);
console.log('icons', Object.keys(out).length, 'missing:', missing.join(' ') || 'none');
