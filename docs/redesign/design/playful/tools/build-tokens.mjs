// Builds tokens/tokens.json, tokens/tokens.css, tokens/theme.css and tokens/CONTRAST.md
// from tools/tokens.source.mjs. Run: node tools/build-tokens.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as T from './tokens.source.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (f, s) => { mkdirSync(dirname(join(root, f)), { recursive: true }); writeFileSync(join(root, f), s); };
const header = '/* Generated by tools/build-tokens.mjs from tools/tokens.source.mjs. Do not edit by hand. */\n';

const decl = (obj, prefix, indent = '  ') =>
  Object.entries(obj).map(([k, v]) => `${indent}--${prefix}${k}: ${v};`).join('\n');

const colorDecl = (mode, indent) => decl(T.semantic[mode], 'color-', indent);
const shadowDecl = (mode, indent) => decl(T.shadow[mode], 'shadow-', indent);

const typeDecl = (indent = '  ') => Object.entries(T.typeScale).map(([k, [size, lh, ls, w, fam]]) => [
  `${indent}--text-${k}: ${size};`,
  `${indent}--text-${k}--line-height: ${lh};`,
  `${indent}--text-${k}--letter-spacing: ${ls};`,
  `${indent}--text-${k}--font-weight: ${w};`,
  `${indent}--text-${k}--font-family: var(--font-${fam});`,
].join('\n')).join('\n');

const staticDecl = (indent = '  ') => [
  decl(T.fonts, 'font-', indent),
  typeDecl(indent),
  `${indent}--spacing: 0.25rem;`,
  decl(Object.fromEntries(Object.entries(T.space).map(([k, v]) => [String(k).replace('.', '_'), v])), 'space-', indent),
  decl(T.radius, 'radius-', indent),
  decl(T.blur, 'blur-', indent),
  decl(T.motion.ease, 'ease-', indent),
].join('\n');

const nonThemeDecl = (indent = '  ') => [
  decl(T.motion.duration, 'duration-', indent),
  decl(T.z, 'z-', indent),
  decl(T.layout, '', indent),
  decl(T.breakpoints, 'breakpoint-', indent),
].join('\n');

const paletteDecl = (indent = '  ') => Object.entries(T.primitives)
  .map(([hue, steps]) => decl(steps, `palette-${hue}-`, indent)).join('\n');

const reducedMotion = `
/* Reduced motion: springs become plain ease-outs and celebrations are skipped.
   Components swap transforms for opacity fades under the same conditions (see assets/css/ui.css). */
@media (prefers-reduced-motion: reduce) {
  :root:not([data-motion="full"]) {
    --ease-spring: var(--ease-out);
    --duration-celebrate: 0ms;
    --duration-sheet: 200ms;
  }
}
:root[data-motion="reduce"] {
  --ease-spring: var(--ease-out);
  --duration-celebrate: 0ms;
  --duration-sheet: 200ms;
}
`;

// ---------- tokens.css (plain CSS custom properties) ----------
const tokensCss = `${header}
/* momoshtrem tokens · Direction B "Playful cat-forward"
   Themes: set data-theme="light" | "dark" on <html> (or any subtree). With no attribute, the OS preference wins. */

:root {
${staticDecl()}
${nonThemeDecl()}
${paletteDecl()}
}

:root,
[data-theme="light"] {
  color-scheme: light;
${colorDecl('light', '  ')}
${shadowDecl('light', '  ')}
}

[data-theme="dark"] {
  color-scheme: dark;
${colorDecl('dark', '  ')}
${shadowDecl('dark', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${colorDecl('dark', '    ')}
${shadowDecl('dark', '    ')}
  }
}
${reducedMotion}`;
out('tokens/tokens.css', tokensCss);

// ---------- theme.css (Tailwind v4, CSS-first) ----------
const themeCss = `${header}
/* Tailwind CSS v4 theme for web/ (momoshtrem-web).
   Usage in src/app/globals.css:
     @import "tailwindcss";
     @import "./theme.css";
   Fonts come from next/font (see HANDOFF.md): it sets --font-fredoka / --font-atkinson / --font-atkinson-mono on <html>.
   Utilities: bg-surface, text-ink-2, border-line, bg-ready-bg text-ready, rounded-lg, shadow-2, text-title-1,
   font-display, ease-spring, tablet:/laptop:/desktop: breakpoints, dark: variant (data-theme="dark"). */

@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));

@theme {
  --breakpoint-*: initial;
  --breakpoint-tablet: ${T.breakpoints.tablet};
  --breakpoint-laptop: ${T.breakpoints.laptop};
  --breakpoint-desktop: ${T.breakpoints.desktop};

  --color-*: initial;
  --color-white: #ffffff;
  --color-black: #000000;
  --color-transparent: transparent;
  --color-current: currentColor;
${colorDecl('light', '  ')}

${staticDecl()}

  --shadow-*: initial;
${shadowDecl('light', '  ')}

  --animate-spin: spin 1s linear infinite;
  --animate-shimmer: shimmer 1.4s var(--ease-in-out) infinite;
  --animate-pop: pop 320ms var(--ease-spring);
  --animate-tail-flick: tail-flick 700ms var(--ease-spring);

  @keyframes spin { to { transform: rotate(360deg); } }
  @keyframes shimmer { from { background-position: 150% 0; } to { background-position: -50% 0; } }
  @keyframes pop { 0% { transform: scale(0.92); } 60% { transform: scale(1.04); } 100% { transform: scale(1); } }
  @keyframes tail-flick { 0%, 100% { transform: rotate(0); } 30% { transform: rotate(-18deg); } 60% { transform: rotate(10deg); } }
}

@layer base {
  :root {
${nonThemeDecl('    ')}
  }
  [data-theme="dark"] {
    color-scheme: dark;
${colorDecl('dark', '    ')}
${shadowDecl('dark', '    ')}
  }
  @media (prefers-color-scheme: dark) {
    :root:not([data-theme="light"]) {
      color-scheme: dark;
${colorDecl('dark', '      ')}
${shadowDecl('dark', '      ')}
    }
  }
}
${reducedMotion}`;
out('tokens/theme.css', themeCss);

// ---------- tokens.json ----------
out('tokens/tokens.json', JSON.stringify({
  $description: 'momoshtrem design tokens, Direction B (Playful cat-forward). Generated from tools/tokens.source.mjs.',
  primitives: T.primitives, color: T.semantic, font: T.fonts,
  text: Object.fromEntries(Object.entries(T.typeScale).map(([k, [size, lineHeight, letterSpacing, weight, family]]) => [k, { size, lineHeight, letterSpacing, weight, family }])),
  space: T.space, radius: T.radius, shadow: T.shadow, blur: T.blur, motion: T.motion, z: T.z,
  breakpoints: T.breakpoints, layout: T.layout,
}, null, 2) + '\n');

// ---------- CONTRAST.md ----------
const hex = (h) => h.replace('#', '').match(/../g).map((x) => parseInt(x, 16) / 255);
const lum = (h) => { const [r, g, b] = hex(h).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };
let md = '# Contrast report\n\nGenerated by `tools/build-tokens.mjs`. WCAG 2.2 AA needs 4.5:1 for body text and 3:1 for large text (24 px+, or 18.66 px bold) and UI parts.\n';
let failures = 0;
for (const mode of ['light', 'dark']) {
  const c = T.semantic[mode];
  md += `\n## ${mode}\n\n| Foreground | Background | Ratio | AA text |\n|---|---|---|---|\n`;
  const pairs = [];
  for (const fg of ['ink', 'ink-2', 'ink-3', 'primary-ink', 'accent-ink', 'ready', 'downloading', 'review', 'warning', 'error', 'missing', 'watched'])
    for (const bg of ['bg', 'surface', 'surface-2', 'raised']) pairs.push([fg, bg]);
  pairs.push(['on-primary', 'primary'], ['primary-soft-ink', 'primary-soft'], ['accent-ink', 'accent-soft'], ['on-sticker', 'butter'], ['on-sticker', 'peach']);
  for (const s of ['ready', 'downloading', 'review', 'warning', 'error', 'watched']) pairs.push([s, `${s}-bg`]);
  pairs.push(['upcoming', 'upcoming-bg']);
  for (const [fg, bg] of pairs) {
    const r = ratio(c[fg], c[bg]);
    const ok = r >= 4.5;
    if (!ok) failures++;
    md += `| \`${fg}\` ${c[fg]} | \`${bg}\` ${c[bg]} | ${r.toFixed(2)} | ${ok ? 'pass' : '**fail**'} |\n`;
  }
}
out('tokens/CONTRAST.md', md);
console.log(`tokens built · contrast failures: ${failures}`);
